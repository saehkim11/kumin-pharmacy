-- 알림 2단계: 알림 주기 규칙(reminder_rules). 실행 순서: 01~25 다음에 실행.
-- 새 테이블과 새 함수만 추가하며 기존 테이블·열·정책·함수는 바꾸지 않는다.
--  - 규칙은 분류(group_name) 또는 상품(product_id) 중 정확히 하나에 붙는다. 상품 규칙이 분류 규칙보다 먼저 적용된다(적용은 3·4단계).
--  - 실제 상품 분류에는 접종(vaccine) 분류가 없다(의약품·사료·보조제·조제·진료뿐). 그래서 접종 안내(정해진 간격)와 재구매 안내
--    (판매 단위 1개당 일수 × 수량)의 구분은 분류가 아니라 규칙의 종류(kind)로 정한다. 분류 규칙은 재구매 안내만 허용한다.
--  - interval_days = 며칠마다 다시 필요한지(재구매 안내는 판매 단위 1개당 일수), lead_days = 며칠 전부터 알림 목록에 올릴지.
--  - 읽기는 직원 이상(판매 화면이 읽는다), 쓰기는 관리자 전용 함수로만 한다.
--  - 값을 정하지 않은 분류·상품은 알림 대상이 아니다(기본값을 넣지 않는다).

create table public.reminder_rules (
  id bigint generated by default as identity primary key,
  group_name text check (group_name is null or group_name in ('drug', 'feed', 'supplement', 'supply', 'vaccine', 'service')),
  product_id int references public.products (id) on delete cascade,
  kind text not null default 'rebuy' check (kind in ('vaccine', 'rebuy')),
  interval_days int not null check (interval_days between 1 and 3650),
  lead_days int not null default 7 check (lead_days between 0 and 365),
  updated_at timestamptz not null default now(),
  updated_by uuid references public.profiles (id),
  constraint reminder_rules_one_key check ((group_name is not null) <> (product_id is not null)),
  constraint reminder_rules_group_rebuy check (group_name is null or kind = 'rebuy')
);
create unique index reminder_rules_group_key on public.reminder_rules (group_name) where group_name is not null;
create unique index reminder_rules_product_key on public.reminder_rules (product_id) where product_id is not null;

alter table public.reminder_rules enable row level security;
grant select on public.reminder_rules to authenticated;
create policy reminder_rules_staff_read on public.reminder_rules for select to authenticated
  using ((select public.is_staff()));

-- 규칙을 저장한다(관리자 전용). 키(분류 또는 상품)는 정확히 하나. p_interval_days가 null이면 그 키의 규칙을 지운다.
create function public.rpc_set_reminder_rule(
  p_group_name text, p_product_id int, p_kind text, p_interval_days int, p_lead_days int
) returns void
language plpgsql security definer set search_path = '' as $$
declare
  v_lead int := coalesce(p_lead_days, 7);
begin
  if not public.is_admin() then raise exception 'forbidden' using errcode = '42501'; end if;
  if (p_group_name is null) = (p_product_id is null) then raise exception 'exactly one of group or product is required'; end if;
  if p_group_name is not null and p_group_name not in ('drug', 'feed', 'supplement', 'supply', 'vaccine', 'service') then
    raise exception 'invalid group';
  end if;
  if p_product_id is not null and not exists (select 1 from public.products where id = p_product_id) then
    raise exception 'product not found';
  end if;

  if p_interval_days is null then   -- 알림 안 함: 규칙 지우기(없어도 오류 아님)
    if p_group_name is not null then
      delete from public.reminder_rules where group_name = p_group_name;
    else
      delete from public.reminder_rules where product_id = p_product_id;
    end if;
    return;
  end if;

  if p_kind is null or p_kind not in ('vaccine', 'rebuy') then raise exception 'invalid kind'; end if;
  if p_group_name is not null and p_kind <> 'rebuy' then raise exception 'group rules must be rebuy'; end if;
  if p_interval_days < 1 or p_interval_days > 3650 then raise exception 'invalid interval'; end if;
  if v_lead < 0 or v_lead > 365 then raise exception 'invalid lead days'; end if;

  if p_group_name is not null then
    insert into public.reminder_rules (group_name, kind, interval_days, lead_days, updated_by)
    values (p_group_name, p_kind, p_interval_days, v_lead, auth.uid())
    on conflict (group_name) where group_name is not null do update
       set kind = excluded.kind, interval_days = excluded.interval_days, lead_days = excluded.lead_days,
           updated_at = now(), updated_by = excluded.updated_by;
  else
    insert into public.reminder_rules (product_id, kind, interval_days, lead_days, updated_by)
    values (p_product_id, p_kind, p_interval_days, v_lead, auth.uid())
    on conflict (product_id) where product_id is not null do update
       set kind = excluded.kind, interval_days = excluded.interval_days, lead_days = excluded.lead_days,
           updated_at = now(), updated_by = excluded.updated_by;
  end if;
end;
$$;

-- 로그인한 사용자만 실행할 수 있게 하고(함수 안에서도 관리자인지 다시 확인한다), 로그인하지 않은 사용자의 실행 권한은 없앤다.
revoke execute on function public.rpc_set_reminder_rule(text, int, text, int, int) from public, anon;
grant execute on function public.rpc_set_reminder_rule(text, int, text, int, int) to authenticated;
