-- 동물약국 ERP 스키마 (Supabase/PostgreSQL). 실행 순서: 01_schema -> 02_security -> 03_rpc
-- 원가·이익 열은 관리자 전용 테이블로 분리한다.

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------- 사용자/권한
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text not null check (char_length(display_name) between 1 and 40),
  role text not null default 'staff' check (role in ('admin', 'staff')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create function public.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles p
                 where p.id = (select auth.uid()) and p.role = 'admin' and p.active);
$$;

create function public.is_staff() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.active);
$$;

-- ---------------------------------------------------------------- 기준정보
create table public.product_categories (
  id int primary key,
  name text not null unique,
  group_name text not null check (group_name in ('drug','feed','supplement','supply','vaccine','service'))
);

create table public.suppliers (
  id int primary key,
  name text not null unique
);

create table public.products (
  id int primary key,
  code text not null unique,
  name text not null,
  barcode text unique,
  category_id int not null references public.product_categories (id),
  target_animal text not null default 'all' check (target_animal in ('all','dog','cat')),
  supplier_id int references public.suppliers (id),
  sale_price numeric(12,0) not null check (sale_price >= 0),
  track_stock boolean not null default true,
  track_expiry boolean not null default false,
  active boolean not null default true
);
create index on public.products (category_id);
create index on public.products (name);

-- 관리자 전용: 기준 매입가
create table public.product_costs (
  product_id int primary key references public.products (id) on delete cascade,
  purchase_price numeric(14,2) not null check (purchase_price >= 0)
);

-- 현재 재고(RPC만 갱신). 이동평균 원가는 관리자 전용 테이블에 분리.
create table public.product_stock (
  product_id int primary key references public.products (id) on delete cascade,
  quantity numeric(12,3) not null default 0 check (quantity >= 0)
);
create table public.product_stock_costs (
  product_id int primary key references public.products (id) on delete cascade,
  avg_cost numeric(14,2) not null default 0 check (avg_cost >= 0)
);

-- ---------------------------------------------------------------- 판매
create table public.sales (
  id bigint generated by default as identity primary key,
  receipt_no text not null unique,
  sold_at timestamptz not null default now(),
  payment_method text not null check (payment_method in ('card','cash')),
  total_amount numeric(14,0) not null check (total_amount >= 0),
  discount_total numeric(14,0) not null default 0 check (discount_total >= 0),
  status text not null default 'completed' check (status in ('completed','cancelled')),
  cancelled_at timestamptz,
  cancel_reason text,
  idempotency_key uuid unique,          -- 중복 요청 방지
  created_by uuid references public.profiles (id)
);
create index on public.sales (sold_at);

create table public.sale_items (
  id bigint generated by default as identity primary key,
  sale_id bigint not null references public.sales (id) on delete cascade,
  product_id int not null references public.products (id),
  quantity numeric(12,3) not null check (quantity > 0),
  unit_price numeric(12,0) not null check (unit_price >= 0),
  discount numeric(12,0) not null default 0 check (discount >= 0),
  amount numeric(14,0) not null check (amount >= 0)
);
create index on public.sale_items (sale_id);
create index on public.sale_items (product_id);

-- 관리자 전용: 판매 시점 원가·매출총이익
create table public.sale_item_costs (
  sale_item_id bigint primary key references public.sale_items (id) on delete cascade,
  unit_cost numeric(14,2) not null check (unit_cost >= 0),
  cost_amount numeric(14,0) not null,
  gross_profit numeric(14,0) not null
);

create table public.payments (
  id bigint generated by default as identity primary key,
  method text not null default 'card' check (method in ('card')),
  approval_no text,
  amount numeric(14,0) not null,
  approved_at timestamptz not null,
  card_company text,
  installment int not null default 0,
  source text not null default 'manual' check (source in ('mock','import','manual'))
);
create table public.payment_matches (
  sale_id bigint primary key references public.sales (id) on delete cascade,
  payment_id bigint not null unique references public.payments (id) on delete cascade,
  status text not null check (status in ('matched','amount_mismatch'))
);

-- ---------------------------------------------------------------- 매입 (관리자 전용)
create table public.purchases (
  id bigint generated by default as identity primary key,
  supplier_id int not null references public.suppliers (id),
  purchased_at date not null,
  received_at date,
  total_amount numeric(14,0) not null default 0
