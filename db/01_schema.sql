create table public.purchase_items (
  id bigint generated by default as identity primary key,
  purchase_id bigint not null references public.purchases (id) on delete cascade,
  product_id int not null references public.products (id),
  quantity numeric(12,3) not null check (quantity > 0),
  unit_cost numeric(14,2) not null check (unit_cost >= 0),
  lot_no text,
  expiry_date date
);
create index on public.purchase_items (purchase_id);
create index on public.purchase_items (product_id);

-- ---------------------------------------------------------------- 재고 이동 원장
create table public.inventory_movements (
  id bigint generated by default as identity primary key,
  product_id int not null references public.products (id),
  moved_at timestamptz not null default now(),
  movement_type text not null check (movement_type in
    ('purchase_in','sale_out','sale_return','vaccination_use','adjustment')),
  quantity numeric(12,3) not null check (quantity <> 0),   -- 입고 +, 출고 -
  ref_type text,
  ref_id bigint
);
create index on public.inventory_movements (product_id, moved_at);
create table public.inventory_movement_costs (            -- 관리자 전용
  movement_id bigint primary key references public.inventory_movements (id) on delete cascade,
  unit_cost numeric(14,2) not null
);

create table public.vaccinations (
  id bigint generated by default as identity primary key,
  administered_on date not null,
  product_id int not null references public.products (id),
  animal_type text not null check (animal_type in ('dog','cat')),
  quantity numeric(12,3) not null check (quantity > 0),
  sale_item_id bigint references public.sale_items (id) on delete set null
  -- 견주·반려동물 식별 정보는 저장하지 않는다.
);

create table public.environmental_data (
  date date primary key,
  temp_max numeric(4,1), temp_min numeric(4,1), temp_mean numeric(4,1),
  precipitation_mm numeric(6,1), humidity_mean numeric(4,1),
  source text
);

-- ---------------------------------------------------------------- 실행 관리(성장 기회 -> 업무)
create table public.action_tasks (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 120),
  description text,
  status text not null default 'todo' check (status in ('todo','doing','done','hold')),
  priority text not null default 'normal' check (priority in ('low','normal','high')),
  due_date date,
  created_by uuid not null references public.profiles (id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table public.task_assignees (
  task_id bigint references public.action_tasks (id) on delete cascade,
  user_id uuid references public.profiles (id) on delete cascade,
  primary key (task_id, user_id)
);
create table public.task_comments (
  id bigint generated by default as identity primary key,
  task_id bigint not null references public.action_tasks (id) on delete cascade,
  author_id uuid not null references public.profiles (id),
  body text not null check (char_length(body) between 1 and 1000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index on public.task_comments (task_id);

-- ---------------------------------------------------------------- 트리거
create function public.set_updated_at() returns trigger
language plpgsql set search_path = '' as $$
begin new.updated_at = now(); return new; end $$;

create trigger trg_tasks_updated before update on public.action_tasks
  for each row execute function public.set_updated_at();
create trigger trg_comments_updated before update on public.task_comments
  for each row execute function public.set_updated_at();

-- 작성자는 서버가 채운다(클라이언트 값 무시)
create function public.set_author() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if tg_table_name = 'action_tasks' then new.created_by = auth.uid();
  else new.author_id = auth.uid(); end if;
  return new;
end $$;
create trigger trg_tasks_author before insert on public.action_tasks
  for each row execute function public.set_author();
create trigger trg_comments_author before insert on public.task_comments
  for each row execute function public.set_author();

-- 직원은 업무의 상태만 바꿀 수 있다
create function public.guard_task_update() returns trigger
language plpgsql set search_path = '' as $$
begin
  if not public.is_admin() and (new.title, new.description, new.priority, new.due_date)
       is distinct from (old.title, old.description, old.priority, old.due_date) then
    raise exception 'staff can only change task status';
  end if;
  return new;
end $$;
create trigger trg_tasks_guard before update on public.action_tasks
  for each row execute function public.guard_task_update();

create function public.guard_comment_update() returns trigger
language plpgsql set search_path = '' as $$
begin
  if new.author_id is distinct from old.author_id or new.task_id is distinct from old.task_id then
    raise exception 'author_id/task_id cannot change';
  end if;
  return new;
end $$;
create trigger trg_comments_guard before update on public.task_comments
  for each row execute function public.guard_comment_update();
