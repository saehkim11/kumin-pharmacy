-- 보호자/반려동물/접종이력 + 음성(이름) 검색 준비. 실행 순서: 01~07 다음에 실행.
-- 음성 UI는 아직 없음 — 여기서는 테이블/인덱스/검색 RPC만 준비한다.

create extension if not exists pg_trgm;

-- ---------------------------------------------------------------- 보호자/반려동물
create table public.owners (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 40),
  phone text,                                   -- 숫자만 저장 (하이픈 제거)
  created_at timestamptz not null default now()
);
create index on public.owners (phone);

create table public.pets (
  id bigint generated by default as identity primary key,
  owner_id bigint not null references public.owners (id) on delete cascade,
  name text not null check (char_length(name) between 1 and 40),
  name_normalized text generated always as (lower(regexp_replace(name, '\s+', '', 'g'))) stored,
  species text not null check (species in ('dog', 'cat', 'unknown')),
  breed text,
  sex text check (sex in ('male', 'female', 'unknown')),
  neutered boolean,
  birth_date date,                              -- 모르면 null, 나이만 알면 비워두고 상세메모에 기록
  coat_color text,
  weight_kg numeric(5,2),
  notes text,                                   -- 진료기록/상세 원본 텍스트
  last_visit_on date,
  created_at timestamptz not null default now()
);
create index on public.pets (owner_id);
create index idx_pets_name_trgm on public.pets using gin (name_normalized gin_trgm_ops);

grant select, insert, update on public.owners, public.pets to authenticated;
alter table public.owners enable row level security;
alter table public.pets enable row level security;

create policy owners_staff_all on public.owners for all to authenticated
  using ((select public.is_staff())) with check ((select public.is_staff()));
create policy pets_staff_all on public.pets for all to authenticated
  using ((select public.is_staff())) with check ((select public.is_staff()));

-- 기존 접종 기록(POS 판매 연동)에 반려동물 연결(선택值, 과거 데이터는 비어 있을 수 있음)
alter table public.vaccinations add column pet_id bigint references public.pets (id) on delete set null;
create index on public.vaccinations (pet_id);

-- ---------------------------------------------------------------- 상품 음성 검색 준비(후순위 구현)
alter table public.products add column if not exists aliases text[] not null default '{}';
create index idx_products_name_trgm on public.products using gin (name gin_trgm_ops);

-- ---------------------------------------------------------------- 보호자 이름 부분 마스킹
create function public.mask_name(p_name text) returns text
language sql immutable set search_path = '' as $$
  select case
    when p_name is null or char_length(p_name) <= 1 then p_name
    else left(p_name, 1) || repeat('○', char_length(p_name) - 1)
  end;
$$;

-- ---------------------------------------------------------------- 동물 이름으로 후보 검색(음성/텍스트 공용)
-- 보호자 연락처는 주지 않는다. 후보 확정 후 rpc_get_pet_detail로 조회.
create function public.rpc_search_pets_by_name(p_name text)
returns table (
  pet_id bigint, pet_name text, species text, breed text,
  sex text, neutered boolean, birth_date date, last_visit_on date,
  owner_name_masked text
)
language sql stable security definer set search_path = '' as $$
  select p.id, p.name, p.species, p.breed, p.sex, p.neutered, p.birth_date, p.last_visit_on,
         public.mask_name(o.name)
  from public.pets p join public.owners o on o.id = p.owner_id
  where public.is_staff()
    and public.similarity(p.name_normalized, lower(regexp_replace(p_name, '\s+', '', 'g'))) > 0.3
  order by public.similarity(p.name_normalized, lower(regexp_replace(p_name, '\s+', '', 'g'))) desc
  limit 20;
$$;

-- ---------------------------------------------------------------- 후보 확정 후 상세 조회(연락처 포함)
create function public.rpc_get_pet_detail(p_pet_id bigint)
returns table (
  pet_id bigint, pet_name text, species text, breed text, sex text, neutered boolean,
  birth_date date, coat_color text, weight_kg numeric, notes text, last_visit_on date,
  owner_name text, owner_phone text
)
language sql stable security definer set search_path = '' as $$
  select p.id, p.name, p.species, p.breed, p.sex, p.neutered,
         p.birth_date, p.coat_color, p.weight_kg, p.notes, p.last_visit_on,
         o.name, o.phone
  from public.pets p join public.owners o on o.id = p.owner_id
  where public.is_staff() and p.id = p_pet_id;
$$;

grant execute on function
  public.mask_name(text),
  public.rpc_search_pets_by_name(text),
  public.rpc_get_pet_detail(bigint)
to authenticated;
