-- 알림 0단계: 보낸 문자 이력(reminder_log)과 보호자별 안내 수신 상태(owner_reminder_pref).
-- 새 테이블·함수만 추가하며 기존 테이블·열·정책·함수는 바꾸지 않는다. 실행 순서: 01~21 다음에 실행.
-- 읽기는 관리자만(RLS), 쓰기는 관리자 전용 SECURITY DEFINER 함수로만 허용한다(기존 패턴).
-- 연락처는 저장하지 않는다. 보낸 문구 사본에는 반려동물 이름이 들어갈 수 있으므로 관리자만 읽을 수 있게 한다.

-- ---------------------------------------------------------------- 보낸 문자 이력
create table public.reminder_log (
  id bigint generated by default as identity primary key,
  client_key uuid not null unique,                -- 화면이 만든 1회용 키. 같은 기록을 두 번 만들지 않게 한다.
  pet_id bigint references public.pets (id) on delete set null,   -- 반려동물을 고르지 않고 보낸 문자는 비어 있다.
  kind text not null check (kind in ('vaccine', 'rebuy', 'task', 'manual')),
  ref_key text check (ref_key is null or char_length(ref_key) <= 60),   -- manual이면 문구 종류(vaccine/reservation/aftercare/custom)
  due_on date,
  status text not null check (status in ('sent', 'skip', 'void')),     -- 보냄 / 넘김 / 되돌림
  message_text text check (message_text is null or char_length(message_text) <= 1000),  -- 실제로 QR에 들어간 문구
  created_at timestamptz not null default now(),
  created_by uuid references public.profiles (id),
  updated_at timestamptz not null default now()
);
create index on public.reminder_log (pet_id, created_at desc);
create index on public.reminder_log (created_at desc);

-- ---------------------------------------------------------------- 보호자별 안내 수신 상태 (행이 없으면 "미확인")
create table public.owner_reminder_pref (
  owner_id bigint primary key references public.owners (id) on delete cascade,
  status text not null check (status in ('consented', 'optout')),      -- 동의 / 거부(거부가 우선)
  status_on date not null default ((now() at time zone 'Asia/Seoul')::date),
  method text check (method is null or method in ('구두', '서면')),
  note text check (note is null or char_length(note) <= 200),
  updated_at timestamptz not null default now(),
  updated_by uuid references public.profiles (id)
);

-- ---------------------------------------------------------------- 읽기 권한(관리자만)
alter table public.reminder_log enable row level security;
alter table public.owner_reminder_pref enable row level security;
grant select on public.reminder_log, public.owner_reminder_pref to authenticated;
create policy reminder_log_admin_read on public.reminder_log for select to authenticated
  using ((select public.is_admin()));
create policy owner_reminder_pref_admin_read on public.owner_reminder_pref for select to authenticated
  using ((select public.is_admin()));

-- ---------------------------------------------------------------- 쓰기 함수(관리자 전용)
-- 문자를 보냈다/넘겼다고 기록한다. 같은 p_client_key로 다시 부르면 새로 만들지 않고 기존 기록의 번호를 돌려준다.
create function public.rpc_log_reminder(
  p_client_key uuid, p_pet_id bigint, p_kind text, p_ref_key text,
  p_due_on date, p_status text, p_message_text text
) returns bigint
language plpgsql security definer set search_path = '' as $$
declare
  v_id bigint;
begin
  if not public.is_admin() then raise exception 'forbidden' using errcode = '42501'; end if;
  if p_client_key is null then raise exception 'client key required'; end if;
  if p_kind is null or p_kind not in ('vaccine', 'rebuy', 'task', 'manual') then raise exception 'invalid kind'; end if;
  if p_status is null or p_status not in ('sent', 'skip') then raise exception 'invalid status'; end if;
  if p_ref_key is not null and char_length(p_ref_key) > 60 then raise exception 'ref key too long'; end if;
  if p_message_text is not null and char_length(p_message_text) > 1000 then raise exception 'message too long'; end if;
  if p_pet_id is not null and not exists (select 1 from public.pets where id = p_pet_id) then
    raise exception 'pet not found';
  end if;

  select r.id into v_id from public.reminder_log r where r.client_key = p_client_key;
  if found then return v_id; end if;

  insert into public.reminder_log (client_key, pet_id, kind, ref_key, due_on, status, message_text, created_by)
  values (p_client_key, p_pet_id, p_kind, nullif(btrim(p_ref_key), ''), p_due_on, p_status, p_message_text, auth.uid())
  on conflict (client_key) do nothing
  returning id into v_id;

  if v_id is null then   -- 동시에 같은 키가 들어온 경우
    select r.id into v_id from public.reminder_log r where r.client_key = p_client_key;
  end if;
  return v_id;
end;
$$;

-- 잘못 누른 기록을 되돌림 처리한다(기록은 남고 상태만 void로 바뀐다). 없거나 이미 되돌린 기록은 오류.
create function public.rpc_void_reminder(p_id bigint)
returns void
language plpgsql security definer set search_path = '' as $$
begin
  if not public.is_admin() then raise exception 'forbidden' using errcode = '42501'; end if;
  update public.reminder_log
     set status = 'void', updated_at = now()
   where id = p_id and status in ('sent', 'skip');
  if not found then raise exception 'reminder not found or already voided'; end if;
end;
$$;

-- 보호자의 안내 수신 상태를 정한다. p_status가 null이면 표시를 지운다(미확인으로 돌아감).
create function public.rpc_set_reminder_pref(p_owner_id bigint, p_status text, p_method text, p_note text)
returns void
language plpgsql security definer set search_path = '' as $$
begin
  if not public.is_admin() then raise exception 'forbidden' using errcode = '42501'; end if;
  if p_owner_id is null or not exists (select 1 from public.owners where id = p_owner_id) then
    raise exception 'owner not found';
  end if;

  if p_status is null then
    delete from public.owner_reminder_pref where owner_id = p_owner_id;
    return;
  end if;

  if p_status not in ('consented', 'optout') then raise exception 'invalid status'; end if;
  if p_method is not null and p_method not in ('구두', '서면') then raise exception 'invalid method'; end if;
  if p_note is not null and char_length(p_note) > 200 then raise exception 'note too long'; end if;

  insert into public.owner_reminder_pref (owner_id, status, status_on, method, note, updated_by)
  values (p_owner_id, p_status, (now() at time zone 'Asia/Seoul')::date, p_method, nullif(btrim(p_note), ''), auth.uid())
  on conflict (owner_id) do update
     set status = excluded.status, status_on = excluded.status_on, method = excluded.method,
         note = excluded.note, updated_at = now(), updated_by = excluded.updated_by;
end;
$$;

grant execute on function
  public.rpc_log_reminder(uuid, bigint, text, text, date, text, text),
  public.rpc_void_reminder(bigint),
  public.rpc_set_reminder_pref(bigint, text, text, text)
to authenticated;

-- 새 함수 3개는 로그인한 사용자만 실행할 수 있게 한다(함수 안에서도 관리자인지 다시 확인한다).
revoke execute on function
  public.rpc_log_reminder(uuid, bigint, text, text, date, text, text),
  public.rpc_void_reminder(bigint),
  public.rpc_set_reminder_pref(bigint, text, text, text)
from public, anon;
