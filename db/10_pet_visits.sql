-- 반려동물 방문별 진료기록/접종이력. 접종관리 시트의 원본 행(날짜별)을 그대로 보존한다.
-- pets.notes는 여러 방문을 이어붙인 요약 텍스트라 날짜별로 쪼개 보여줄 수 없어서 별도 테이블로 분리.

create table public.pet_visits (
  id bigint generated by default as identity primary key,
  pet_id bigint not null references public.pets (id) on delete cascade,
  visit_date date,
  record text,   -- 진료기록 원문
  detail text    -- 상세 원문
);
create index on public.pet_visits (pet_id, visit_date);

alter table public.pet_visits enable row level security;
grant select on public.pet_visits to authenticated;
create policy pet_visits_staff_read on public.pet_visits for select to authenticated
  using ((select public.is_staff()));
