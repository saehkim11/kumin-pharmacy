-- 엑셀(판매관리) 과거 판매 이력 보관용. 결제수단 정보가 없어서 기존 sales/sale_items와는 분리한다.
-- 원가·손익이 섞여 있어 관리자만 조회(기존 원가 테이블과 같은 패턴).

create table public.sales_legacy (
  id bigint generated by default as identity primary key,
  sold_on date not null,
  product_id int references public.products (id),
  product_name_raw text not null,
  unit_label text,
  quantity numeric(12,3),
  unit_price numeric(12,0),
  amount numeric(14,0),
  unit_cost numeric(14,2),
  profit numeric(14,0),
  margin_rate numeric(8,4),
  imported_at timestamptz not null default now()
);
create index on public.sales_legacy (sold_on);
create index on public.sales_legacy (product_id);

alter table public.sales_legacy enable row level security;
grant select on public.sales_legacy to authenticated;
create policy sales_legacy_admin_read on public.sales_legacy for select to authenticated
  using ((select public.is_admin()));
